/* ──────────────────────────────────────────────────────────────────
 * Alloy renderer — uses native `@alloy-js/python` components
 * (ClassDeclaration, MethodDeclaration, FunctionDeclaration, …) for
 * all structural Python constructs. Method bodies remain as string
 * children — the imperative logic (LRO polling, paging closures,
 * dict serialisation) is naturally expressed as text, not as a JSX
 * component tree. Imports are string-based because setting up Alloy
 * external modules for every azure-core symbol would be overkill for
 * a benchmark sandbox.
 * ────────────────────────────────────────────────────────────── */

