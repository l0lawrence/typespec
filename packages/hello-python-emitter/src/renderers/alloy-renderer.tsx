/* ═══════════════════════  Helpers  ════════════════════════════════ */

function fmtPath(op: SdkOperation): string {
  if (op.pathParameters.length === 0) return `"${op.path}"`;
  let s = op.path;
  for (const p of op.pathParameters) s = s.replace(`{${p.serializedName}}`, `{${p.pyName}}`);
  return `f"${s}"`;
}

function decodeScalar(t: string, src: string): string {
  if (["str", "bool", "int", "float", "Any", "bytes"].includes(t)) return src;
  if (t === "datetime.datetime") return `_parse_datetime(${src})`;
  if (["datetime.date", "datetime.time", "datetime.timedelta"].includes(t)) return src;
  if (t === "decimal.Decimal") return `decimal.Decimal(${src}) if ${src} is not None else None`;
  return `_from_dict(${t}, ${src})`;
}

function decodeExpr(p: SdkProperty): string {
  const key = `data.get("${p.serializedName}")`;
  const t = p.pyType;
  if (t.startsWith("list["))
    return `[${decodeScalar(t.slice(5, -1), "v")} for v in (${key} or [])]`;
  if (t.startsWith("dict[")) return key;
  return decodeScalar(t, key);
}

type Param = alloyPy.ParameterDescriptor | "*" | "/";

/* ═══════════════════  Model class  ═══════════════════════════════ */

function renderModelClass(m: SdkModel) {
  const req = m.properties.filter((p) => !p.optional);
  const opt = m.properties.filter((p) => p.optional);

  if (m.properties.length === 0) {
    return (
      <alloyPy.ClassDeclaration name={m.pyName}>
        {`"""${docstring(m.docstring ?? m.name)}"""\npass`}
      </alloyPy.ClassDeclaration>
    );
  }

  const preamble = [
    `"""${docstring(m.docstring ?? m.name)}"""`,
    "",
    ...req.map((p) => `${p.pyName}: ${p.pyType}`),
    ...opt.map((p) => `${p.pyName}: Optional[${p.pyType}] = None`),
    "",
    "_SERIALIZED_NAMES: ClassVar[Dict[str, str]] = {",
    ...m.properties.map((p) => `    "${p.pyName}": "${p.serializedName}",`),
    "}",
  ].join("\n");

  const initParams: Param[] = [
    "*",
    ...req.map((p): alloyPy.ParameterDescriptor => ({ name: p.pyName, type: p.pyType })),
    ...opt.map(
      (p): alloyPy.ParameterDescriptor => ({
        name: p.pyName,
        type: `Optional[${p.pyType}]`,
        default: null as any,
      }),
    ),
  ];

  const initBody = m.properties.map((p) => `self.${p.pyName} = ${p.pyName}`).join("\n");

  const asDictBody = [
    "d: Dict[str, Any] = {}",
    ...m.properties.map(
      (p) =>
        `if self.${p.pyName} is not None:\n    d["${p.serializedName}"] = _to_dict(self.${p.pyName})`,
    ),
    "return d",
  ].join("\n");

  const fromDictBody = [
    "return cls(",
    ...m.properties.map((p) => `    ${p.pyName}=${decodeExpr(p)},`),
    ")",
  ].join("\n");

  return (
    <alloyPy.ClassDeclaration name={m.pyName}>
      {preamble + "\n"}

      <alloyPy.DunderMethodDeclaration name="__init__" parameters={initParams} returnType="None">
        {initBody}
      </alloyPy.DunderMethodDeclaration>
      {"\n"}
      <alloyPy.MethodDeclaration name="as_dict" returnType="Dict[str, Any]">
        {asDictBody}
      </alloyPy.MethodDeclaration>
      {"\n"}
      <alloyPy.ClassMethodDeclaration
        name="from_dict"
        parameters={[{ name: "data", type: "Mapping[str, Any]" }]}
        returnType={`"${m.pyName}"`}
      >
        {fromDictBody}
      </alloyPy.ClassMethodDeclaration>
    </alloyPy.ClassDeclaration>
  );
}

/* ═══════════════════  Enum class  ════════════════════════════════ */

function renderEnumClass(e: SdkEnum) {
  const body = [
    `"""${docstring(e.docstring ?? e.name)}"""`,
    ...e.members.map((m) => `${m.pyName} = "${m.value}"`),
  ].join("\n");

  return (
    <alloyPy.ClassDeclaration name={e.pyName} bases={["str", "Enum"]}>
      {body}
    </alloyPy.ClassDeclaration>
  );
}

/* ═══════════════════  Operation method body  ═════════════════════ */

function buildOpBody(op: SdkOperation): string {
  const lines: string[] = [];
  const pathExpr = fmtPath(op);

  const queryParts = ["**_api_version_query(self._config)"];
  for (const p of op.queryParameters) {
    if (p.serializedName === "api-version") continue;
    queryParts.push(`"${p.serializedName}": ${p.pyName}`);
  }

  const headerParts: string[] = [];
  const hasUserCt = op.headerParameters.some(
    (p) => p.serializedName.toLowerCase() === "content-type",
  );
  if (op.bodyParameter) {
    const ct =
      hasUserCt && op.verb === "patch" ? "application/merge-patch+json" : "application/json";
    headerParts.push(`"Content-Type": "${ct}"`);
  }
  for (const p of op.headerParameters) {
    if (p.serializedName.toLowerCase() === "content-type") continue;
    headerParts.push(`"${p.serializedName}": ${p.pyName}`);
  }

  lines.push(`_params: dict = {${queryParts.join(", ")}}`);
  if (op.queryParameters.some((p) => p.serializedName !== "api-version")) {
    lines.push("_params = {k: v for k, v in _params.items() if v is not None}");
  }
  if (headerParts.length) {
    lines.push(`_headers: dict = {${headerParts.join(", ")}}`);
    lines.push("_headers = {k: v for k, v in _headers.items() if v is not None}");
  }
  if (op.bodyParameter) {
    lines.push(`_body = _to_dict(${op.bodyParameter.pyName})`);
  }

  if (op.paged) {
    lines.push("def _prepare(next_link: Optional[str] = None) -> HttpRequest:");
    lines.push("    if next_link is None:");
    lines.push(
      `        return HttpRequest("${op.verb.toUpperCase()}", ${pathExpr}, params=_params${headerParts.length ? ", headers=_headers" : ""})`,
    );
    lines.push('    return HttpRequest("GET", next_link)');
    lines.push("");
    lines.push("def _extract(pipeline_response):");
    lines.push("    payload = pipeline_response.http_response.json()");
    lines.push(
      `    items = [_from_dict(${op.paged.itemPyType}, v) for v in payload.get("${op.paged.itemsPath}", [])]`,
    );
    lines.push(`    return payload.get("${op.paged.nextLinkPath ?? "nextLink"}"), iter(items)`);
    lines.push("");
    lines.push("def _get_next(next_link: Optional[str] = None):");
    lines.push("    request = _prepare(next_link)");
    lines.push("    return self._client._pipeline.run(request, stream=False, **kwargs)");
    lines.push("");
    lines.push("return ItemPaged(_get_next, _extract)");
    return lines.join("\n");
  }

  const extras = ["params=_params"];
  if (headerParts.length) extras.push("headers=_headers");
  if (op.bodyParameter) extras.push("json=_body");
  lines.push(
    `_request = HttpRequest("${op.verb.toUpperCase()}", ${pathExpr}, ${extras.join(", ")})`,
  );

  if (op.lro) {
    const expected = op.successStatusCodes.length ? op.successStatusCodes : [200, 201, 202, 204];
    lines.push("_initial = self._client.send_request(_request, **kwargs)");
    lines.push(`if _initial.status_code not in ${formatTuple(expected)}:`);
    lines.push("    raise HttpResponseError(response=_initial)");
    lines.push(
      '_polling = LROBasePolling(lro_options={"final-state-via": "azure-async-operation"}, **kwargs)',
    );
    lines.push("def _deserialize(pipeline_response):");
    if (op.lro.finalPyType === "None") {
      lines.push("    return None");
    } else {
      lines.push(
        "    payload = pipeline_response.http_response.json() if pipeline_response.http_response.content else None",
      );
      lines.push(`    return _from_dict(${op.lro.finalPyType}, payload)`);
    }
    lines.push("return LROPoller(self._client, _initial, _deserialize, _polling)");
    return lines.join("\n");
  }

  lines.push("_response = self._client.send_request(_request, **kwargs)");
  const expectedSc = op.successStatusCodes.length ? op.successStatusCodes : [200];
  lines.push(`if _response.status_code not in ${formatTuple(expectedSc)}:`);
  lines.push("    raise HttpResponseError(response=_response)");
  if (op.returnPyType === "None") {
    lines.push("return None");
  } else {
    lines.push("_payload = _response.json() if _response.content else None");
    lines.push(
      `return _from_dict(${stripOptional(op.returnPyType)}, _payload)  # type: ignore[return-value]`,
    );
  }
  return lines.join("\n");
}

/* ═══════════════════  Operation method component  ════════════════ */

function renderOperationMethod(op: SdkOperation) {
  const isLro = !!op.lro;
  const isPaged = !!op.paged;
  const methodName = isLro ? `begin_${op.pyName.replace(/^(begin_)?/, "")}` : op.pyName;
  const returnType = isLro
    ? `LROPoller[${op.lro!.finalPyType}]`
    : isPaged
      ? `ItemPaged[${op.paged!.itemPyType}]`
      : op.returnPyType;

  const params: Param[] = [];
  for (const p of op.pathParameters) params.push({ name: p.pyName, type: p.pyType });
  if (op.bodyParameter)
    params.push({ name: op.bodyParameter.pyName, type: op.bodyParameter.pyType });

  const kwOnly: Param[] = [];
  for (const p of op.queryParameters) {
    if (p.serializedName === "api-version") continue;
    kwOnly.push({ name: p.pyName, type: `Optional[${p.pyType}]`, default: null as any });
  }
  for (const p of op.headerParameters) {
    if (p.serializedName.toLowerCase() === "content-type") continue;
    kwOnly.push({ name: p.pyName, type: `Optional[${p.pyType}]`, default: null as any });
  }
  if (kwOnly.length) {
    params.push("*");
    params.push(...kwOnly);
  }

  return (
    <alloyPy.MethodDeclaration name={methodName} parameters={params} kwargs returnType={returnType}>
      {`"""${docstring(op.docstring ?? op.name)}"""\n${buildOpBody(op)}`}
    </alloyPy.MethodDeclaration>
  );
}

