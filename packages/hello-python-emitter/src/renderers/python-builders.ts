export function buildTopInit(rendererId: string, shape: SdkShape): string {
  return [
    header(rendererId),
    `from ._client import ${shape.clientName}`,
    "from ._version import VERSION as __version__",
    "",
    `__all__ = ["${shape.clientName}", "__version__"]`,
    "",
  ].join("\n");
}

export function buildVersion(rendererId: string, shape: SdkShape): string {
  return `${header(rendererId)}\nVERSION = "${shape.version}"\n`;
}

export function buildOperationsInit(rendererId: string, opsClass: string): string {
  return `${header(rendererId)}\nfrom ._operations import ${opsClass}\n\n__all__ = ["${opsClass}"]\n`;
}

export function buildModelsInit(rendererId: string, shape: SdkShape): string {
  const lines: string[] = [header(rendererId)];
  if (shape.models.length) {
    lines.push(`from ._models import ${shape.models.map((m) => m.pyName).join(", ")}`);
  }
  if (shape.enums.length) {
    lines.push(`from ._enums import ${shape.enums.map((e) => e.pyName).join(", ")}`);
  }
  const all = [...shape.models.map((m) => m.pyName), ...shape.enums.map((e) => e.pyName)];
  lines.push("");
  if (all.length) {
    lines.push(`__all__ = [${all.map((n) => `"${n}"`).join(", ")}]`);
  } else {
    lines.push("__all__: list[str] = []");
  }
  lines.push("");
  return lines.join("\n");
}

